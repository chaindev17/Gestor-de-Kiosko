export function getTodayIso() {
  return new Date().toISOString().slice(0, 10);
}

export function getCurrentPeriod() {
  return new Date().toISOString().slice(0, 7);
}

export function getNextBusinessDayIso(dateIso) {
  const base = new Date(`${dateIso}T12:00:00Z`);
  base.setUTCDate(base.getUTCDate() + 1);
  // Skip Saturday (6) and Sunday (0) for Cuban banking days
  while (base.getUTCDay() === 0 || base.getUTCDay() === 6) {
    base.setUTCDate(base.getUTCDate() + 1);
  }
  return base.toISOString().slice(0, 10);
}

export function getOnatDueDate(period) {
  const [yStr, mStr] = period.split('-');
  let year = Number(yStr);
  let month = Number(mStr) + 1;
  if (month > 12) {
    month = 1;
    year += 1;
  }
  return `${year}-${String(month).padStart(2, '0')}-20`;
}


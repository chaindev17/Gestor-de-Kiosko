/**
 * Automated double-entry accounting entry following Cuban NCIF standards.
 */
export function postJournalEntry(
  db,
  { entryDate, sourceType, sourceRef = '', description, lines, createdBy = null, autoGenerated = 1, silent = false }
) {
  const cleanLines = lines
    .map((l) => ({
      account_code: l.account.code,
      account_name: l.account.name,
      debit_cup: roundCup(l.debit || 0),
      credit_cup: roundCup(l.credit || 0),
    }))
    .filter((l) => l.debit_cup > 0 || l.credit_cup > 0);

  if (cleanLines.length === 0) return null;

  const totalDebit = roundCup(cleanLines.reduce((acc, l) => acc + l.debit_cup, 0));
  const totalCredit = roundCup(cleanLines.reduce((acc, l) => acc + l.credit_cup, 0));

  if (Math.abs(totalDebit - totalCredit) > 0.02) {
    throw new Error(
      `Asiento contable descuadrado (NCIF): Debe (${totalDebit} CUP) != Haber (${totalCredit} CUP).`
    );
  }

  // Adjust potential 0.01 rounding discrepancy on last credit line
  if (totalDebit !== totalCredit) {
    const diff = roundCup(totalDebit - totalCredit);
    const creditLine = [...cleanLines].reverse().find((l) => l.credit_cup > 0);
    if (creditLine) creditLine.credit_cup = roundCup(creditLine.credit_cup + diff);
  }

  const finalTotal = roundCup(cleanLines.reduce((acc, l) => acc + l.debit_cup, 0));
  const entryNumber = nextDocCode(db, 'journal_entries', 'entry_number', 'AST', 5);
  const dateStr = entryDate || getTodayIso();

  const res = db
    .prepare(
      `INSERT INTO journal_entries
       (entry_number, entry_date, source_type, source_ref, description, total_debit_cup, total_credit_cup, auto_generated, created_by)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`
    )
    .run(entryNumber, dateStr, sourceType, sourceRef, description, finalTotal, finalTotal, autoGenerated ? 1 : 0, createdBy);

  const entryId = Number(res.lastInsertRowid);
  const insertLine = db.prepare(
    `INSERT INTO journal_lines (journal_entry_id, account_code, account_name, debit_cup, credit_cup)
     VALUES (?, ?, ?, ?, ?)`
  );
  for (const line of cleanLines) {
    insertLine.run(entryId, line.account_code, line.account_name, line.debit_cup, line.credit_cup);
  }

  if (!silent && autoGenerated) {
    logAutomation(
      db,
      'CONTABILIDAD',
      'INFO',
      `Asiento NCIF ${entryNumber} contabilizado`,
      `${description} — Partida doble por ${finalTotal.toFixed(2)} CUP.`,
      entryNumber
    );
  }

  return { id: entryId, entryNumber, total: finalTotal };
}

/**
 * MFP Cost Sheet (Ficha de Costo y Precio) + Res. 225/2024 price cap calculator.
 */
export function calculateCostSheet(product, config) {
  const unitCost = roundCup(product.unit_cost_cup || 0);
  const indirectPct =
    product.indirect_cost_pct !== undefined && product.indirect_cost_pct !== null
      ? Number(product.indirect_cost_pct)
      : Number(config.indirect_cost_alloc_pct || 8);
  const indirectAmount = roundCup((unitCost * indirectPct) / 100);
  const fullCost = roundCup(unitCost + indirectAmount);
  const maxMarginPct = Number(config.max_regulated_margin_pct || 30);
  const maxPriceByMargin = fullCost > 0 ? roundCup(fullCost * (1 + maxMarginPct / 100)) : 0;

  const isPriceCapped = Boolean(product.is_price_capped) && Number(product.price_cap_cup) > 0;
  const priceCap = isPriceCapped ? roundCup(product.price_cap_cup) : null;
  const isMarginRegulated = Boolean(product.is_margin_regulated);

  let legalMaxPrice = null;
  if (isPriceCapped && isMarginRegulated && maxPriceByMargin > 0) {
    legalMaxPrice = roundCup(Math.min(priceCap, maxPriceByMargin));
  } else if (isPriceCapped) {
    legalMaxPrice = priceCap;
  } else if (isMarginRegulated && maxPriceByMargin > 0) {
    legalMaxPrice = maxPriceByMargin;
  }

  // Suggested price rounded down to whole CUP so it never exceeds legal cap
  let suggestedPrice = fullCost > 0 ? Math.floor(fullCost * (1 + Math.min(maxMarginPct, 26) / 100)) : 0;
  if (legalMaxPrice !== null && suggestedPrice > legalMaxPrice) {
    suggestedPrice = Math.floor(legalMaxPrice);
  }
  if (suggestedPrice < fullCost && (legalMaxPrice === null || Math.ceil(fullCost) <= legalMaxPrice)) {
    suggestedPrice = Math.min(legalMaxPrice ?? Math.ceil(fullCost), Math.ceil(fullCost));
  }

  const salePrice = roundCup(product.sale_price_cup || 0);
  const unitProfit = roundCup(salePrice - fullCost);
  const marginOverFullCostPct = fullCost > 0 ? roundCup(((salePrice - fullCost) / fullCost) * 100) : 0;
  const grossMarginOverCostPct = unitCost > 0 ? roundCup(((salePrice - unitCost) / unitCost) * 100) : 0;

  const exceedsCap = isPriceCapped && salePrice > priceCap + 0.005;
  const exceedsMargin = isMarginRegulated && fullCost > 0 && salePrice > maxPriceByMargin + 0.02;
  const belowCost = fullCost > 0 && salePrice < fullCost - 0.01;

  let complianceStatus = 'OK';
  let complianceNote = 'Cumple Ficha de Costo MFP';
  if (exceedsCap) {
    complianceStatus = 'VIOLACION_TOPE';
    complianceNote = `Excede tope oficial de ${priceCap} CUP (${product.price_cap_resolution || 'MFP'})`;
  } else if (exceedsMargin) {
    complianceStatus = 'EXCESO_MARGEN';
    complianceNote = `Supera el ${maxMarginPct}% de margen máximo MFP (${marginOverFullCostPct}%)`;
  } else if (belowCost) {
    complianceStatus = 'BAJO_COSTO';
    complianceNote = `Precio inferior al costo total reconocido (${fullCost} CUP)`;
  }

  return {
    unit_cost_cup: unitCost,
    indirect_pct: indirectPct,
    indirect_amount_cup: indirectAmount,
    full_cost_cup: fullCost,
    max_margin_pct: maxMarginPct,
    max_price_by_margin_cup: maxPriceByMargin,
    price_cap_cup: priceCap,
    legal_max_price_cup: legalMaxPrice,
    suggested_price_cup: roundCup(suggestedPrice),
    sale_price_cup: salePrice,
    unit_profit_cup: unitProfit,
    margin_pct: marginOverFullCostPct,
    gross_markup_pct: grossMarginOverCostPct,
    exceeds_cap: exceedsCap,
    exceeds_margin: exceedsMargin,
    below_cost: belowCost,
    compliance_status: complianceStatus,
    compliance_note: complianceNote,
  };
}

/**
 * Validates a proposed retail price against Cuban MFP Res. 225/2024 caps & 30% max margin.
 */
export function validateProposedPrice(product, proposedPrice, config) {
  const price = roundCup(proposedPrice);
  if (price <= 0) {
    return { valid: false, message: 'El precio de venta en CUP debe ser mayor que cero.' };
  }
  const sheet = calculateCostSheet({ ...product, sale_price_cup: price }, config);
  if (sheet.exceeds_cap && config.strict_price_cap_block) {
    return {
      valid: false,
      sheet,
      message: `Bloqueado por ${product.price_cap_resolution || 'Res. 225/2024 MFP'} / Decreto 30: "${product.name}" tiene precio minorista topado en ${sheet.price_cap_cup.toFixed(2)} CUP/${product.unit}. No puede fijarse en ${price.toFixed(2)} CUP.`,
    };
  }
  if (sheet.exceeds_margin && config.strict_price_cap_block) {
    return {
      valid: false,
      sheet,
      message: `Bloqueado por normativa MFP: El precio ${price.toFixed(2)} CUP genera un margen de ${sheet.margin_pct}% sobre costos y gastos reconocidos (${sheet.full_cost_cup.toFixed(2)} CUP), superando el límite del ${sheet.max_margin_pct}% (máximo permitido: ${sheet.max_price_by_margin_cup.toFixed(2)} CUP).`,
    };
  }
  return { valid: true, sheet, warning: sheet.below_cost ? sheet.compliance_note : null };
}

/**
 * Validates BCC Resolución 111/2023 (Bancarización) on supplier & expense payments.
 */
export function validateBancarizacionPayment(amountCup, paymentMethod, paymentRef, config) {
  const amount = roundCup(amountCup);
  const limit = Number(config.max_cash_provider_payment_cup || 5000);
  if (paymentMethod === 'EFECTIVO' && amount > limit) {
    const msg = `Resolución 111/2023 del BCC (Bancarización): Las operaciones entre actores económicos superiores a ${limit.toFixed(2)} CUP (${amount.toFixed(2)} CUP) deben pagarse obligatoriamente por transferencia o pasarela electrónica (Transfermóvil / EnZona).`;
    if (config.strict_bancarizacion_block) {
      return { valid: false, blocked: true, message: msg };
    }
    return { valid: true, blocked: false, warning: msg };
  }
  if (['TRANSFERENCIA', 'TRANSFERMOVIL', 'ENZONA'].includes(paymentMethod) && !String(paymentRef || '').trim()) {
    return {
      valid: false,
      blocked: true,
      message:
        'Para pagos electrónicos/bancarios es obligatorio consignar el número de referencia u operación para conciliación de la Cuenta Bancaria Fiscal.',
    };
  }
  return { valid: true, blocked: false };
}

/**
 * Cuban progressive monthly Personal Income Tax (Impuesto sobre los Ingresos Personales - Ley 113).
 */
export function calculateMonthlyIIP(grossMonthlyCup, exemptCup = 3260) {
  const income = roundCup(grossMonthlyCup);
  const exempt = Number(exemptCup || 3260);
  if (income <= exempt) return 0;

  const brackets = [
    { from: exempt, to: 9510, rate: 0.03 },
    { from: 9510, to: 15000, rate: 0.05 },
    { from: 15000, to: 20000, rate: 0.075 },
    { from: 20000, to: 25000, rate: 0.1 },
    { from: 25000, to: 30000, rate: 0.15 },
    { from: 30000, to: Infinity, rate: 0.2 },
  ];

  let tax = 0;
  for (const b of brackets) {
    if (income > b.from && b.to > b.from) {
      const slice = Math.min(income, b.to) - b.from;
      tax += slice * b.rate;
    }
  }
  return roundCup(tax);
}

/**
 * Cuban Worker Special Social Security Contribution (Contribución Especial a la Seguridad Social).
 * 5% up to 15,000 CUP and 10% on any amount above 15,000 CUP.
 */
export function calculateWorkerSS(grossMonthlyCup, baseRatePct = 5.0) {
  const income = roundCup(grossMonthlyCup);
  if (income <= 0) return 0;
  const baseRate = Number(baseRatePct || 5) / 100;
  if (income <= 15000) {
    return roundCup(income * baseRate);
  }
  const baseTax = 15000 * baseRate;
  const excessTax = (income - 15000) * Math.max(baseRate, 0.1);
  return roundCup(baseTax + excessTax);
}

/**
 * Calculates full automated payroll preview for a YYYY-MM period, pulling shift counts
 * and individual seller sales directly from completed kiosk shifts.
 */
export function calculatePayrollPreview(db, period) {
  const config = getConfig(db);
  const employees = db
    .prepare(
      `SELECT u.*, st.name AS shift_name
       FROM users u
       LEFT JOIN shift_templates st ON st.id = u.shift_template_id
       WHERE u.active = 1
       ORDER BY CASE u.role
         WHEN 'jefe' THEN 1
         WHEN 'economico' THEN 2
         WHEN 'almacenero' THEN 3
         WHEN 'vendedor' THEN 4
       END, u.id`
    )
    .all();

  const items = employees.map((emp) => {
    const salesRow = db
      .prepare(
        `SELECT COALESCE(SUM(total_cup), 0) AS sales_total
         FROM sales
         WHERE seller_id = ? AND status = 'COMPLETADA' AND substr(sale_date, 1, 7) = ?`
      )
      .get(emp.id, period);

    const shiftsRow = db
      .prepare(
        `SELECT COUNT(*) AS cnt
         FROM shift_registers sr
         JOIN shift_sessions ss ON ss.id = sr.shift_session_id
         WHERE sr.seller_id = ? AND substr(ss.work_date, 1, 7) = ?`
      )
      .get(emp.id, period);

    const sellerSales = roundCup(salesRow?.sales_total || 0);
    const shiftsWorked = Number(shiftsRow?.cnt || 0);
    const baseSalary = roundCup(emp.base_salary_cup);
    const commission =
      emp.role === 'vendedor' && emp.sales_commission_pct > 0
        ? roundCup((sellerSales * Number(emp.sales_commission_pct)) / 100)
        : 0;
    const grossSalary = roundCup(baseSalary + commission);

    // TCP titular does not pay worker withholding via payroll (pays via DJ-08 & special regime)
    const isTcpOwner = config.legal_form === 'TCP' && emp.role === 'jefe';

    const vacationAccrual = isTcpOwner
      ? 0
      : roundCup((grossSalary * Number(config.vacation_provision_pct)) / 100);
    const workerSS = isTcpOwner ? 0 : calculateWorkerSS(grossSalary, config.worker_ss_pct);
    const workerIIP = isTcpOwner ? 0 : calculateMonthlyIIP(grossSalary, config.iip_exempt_monthly_cup);
    const netSalary = roundCup(grossSalary - workerSS - workerIIP);
    const employerSS = isTcpOwner ? 0 : roundCup((grossSalary * Number(config.employer_ss_pct)) / 100);
    const laborTax = isTcpOwner
      ? 0
      : roundCup(((grossSalary + vacationAccrual) * Number(config.labor_force_tax_pct)) / 100);

    return {
      user_id: emp.id,
      full_name: emp.full_name,
      role: emp.role,
      shift_name: emp.shift_name || 'Jornada General',
      ci: emp.ci,
      contract_type: emp.contract_type,
      shifts_worked: shiftsWorked,
      seller_sales_cup: sellerSales,
      sales_commission_pct: emp.sales_commission_pct,
      base_salary_cup: baseSalary,
      commission_cup: commission,
      gross_salary_cup: grossSalary,
      vacation_accrual_cup: vacationAccrual,
      worker_ss_cup: workerSS,
      worker_iip_cup: workerIIP,
      net_salary_cup: netSalary,
      employer_ss_cup: employerSS,
      labor_tax_cup: laborTax,
      is_tcp_owner: isTcpOwner,
      below_min_wage: baseSalary < Number(config.min_wage_cup),
    };
  });

  const totals = {
    period,
    employee_count: items.length,
    total_gross_cup: roundCup(items.reduce((a, i) => a + i.gross_salary_cup, 0)),
    total_vacation_accrual_cup: roundCup(items.reduce((a, i) => a + i.vacation_accrual_cup, 0)),
    total_worker_ss_cup: roundCup(items.reduce((a, i) => a + i.worker_ss_cup, 0)),
    total_worker_iip_cup: roundCup(items.reduce((a, i) => a + i.worker_iip_cup, 0)),
    total_net_cup: roundCup(items.reduce((a, i) => a + i.net_salary_cup, 0)),
    total_employer_ss_cup: roundCup(items.reduce((a, i) => a + i.employer_ss_cup, 0)),
    total_labor_tax_cup: roundCup(items.reduce((a, i) => a + i.labor_tax_cup, 0)),
  };
  totals.total_employer_cost_cup = roundCup(
    totals.total_gross_cup +
      totals.total_vacation_accrual_cup +
      totals.total_employer_ss_cup +
      totals.total_labor_tax_cup
  );

  return { config, items, totals };
}

/**
 * Automatic Kiosk Restock Engine: detects low stock on the sales floor and generates/updates
 * a dispatch request for the Almacenero automatically.
 */
export function checkAndTriggerAutoRestock(db, productId) {
  const config = getConfig(db);
  if (!config.auto_restock_enabled) return null;

  const product = db.prepare('SELECT * FROM products WHERE id = ? AND active = 1').get(productId);
  if (!product) return null;

  if (product.kiosk_stock > product.kiosk_min_stock) return null;

  const needed = roundCup(Math.max(1, product.kiosk_target_stock - product.kiosk_stock));
  const dispatchable = roundCup(Math.min(product.warehouse_stock, needed));
  const priority = product.kiosk_stock <= Math.max(1, product.kiosk_min_stock * 0.4) ? 'URGENTE' : 'NORMAL';

  if (dispatchable <= 0) {
    logAutomation(
      db,
      'ALMACEN',
      'ALERTA',
      `Desabastecimiento detectado: ${product.name}`,
      `Stock en mostrador (${product.kiosk_stock} ${product.unit}) bajo el mínimo y sin respaldo en almacén. Requiere compra a proveedor.`,
      product.sku
    );
    return { status: 'NO_WAREHOUSE_STOCK', product };
  }

  const existing = db
    .prepare(`SELECT * FROM restock_requests WHERE product_id = ? AND status = 'PENDIENTE'`)
    .get(productId);

  if (existing) {
    db.prepare(
      `UPDATE restock_requests SET suggested_qty = ?, priority = ? WHERE id = ?`
    ).run(dispatchable, priority, existing.id);
    return { id: existing.id, suggested_qty: dispatchable, priority, updated: true };
  }

  const note = product.next_expiry_date
    ? `Auto-generado (FEFO: despachar lote ${product.current_batch || 'actual'}, vence ${product.next_expiry_date})`
    : `Auto-generado al bajar de ${product.kiosk_min_stock} ${product.unit} en mostrador`;

  const res = db
    .prepare(
      `INSERT INTO restock_requests (product_id, suggested_qty, origin, priority, status, notes)
       VALUES (?, ?, 'AUTOMATICO', ?, 'PENDIENTE', ?)`
    )
    .run(productId, dispatchable, priority, note);

  logAutomation(
    db,
    'ALMACEN',
    priority === 'URGENTE' ? 'ALERTA' : 'INFO',
    `Orden automática de reabastecimiento: ${product.name}`,
    `Mostrador en ${product.kiosk_stock} ${product.unit} (mín. ${product.kiosk_min_stock}). Solicitados ${dispatchable} ${product.unit} al Almacenero.`,
    product.sku
  );

  return { id: Number(res.lastInsertRowid), suggested_qty: dispatchable, priority, created: true };
}

/**
 * Calculates full monthly ONAT tax liquidation & P&L statement according to Ley 113 & DL 88/90.
 */
export function calculateOnatSummary(db, period) {
  const config = getConfig(db);
  const dueDate = getOnatDueDate(period);

  const salesAgg = db
    .prepare(
      `SELECT
         COUNT(*) AS sales_count,
         COALESCE(SUM(subtotal_cup), 0) AS subtotal_cup,
         COALESCE(SUM(qr_discount_cup), 0) AS qr_discount_cup,
         COALESCE(SUM(total_cup), 0) AS gross_sales_cup,
         COALESCE(SUM(total_cost_cup), 0) AS cogs_cup,
         COALESCE(SUM(cash_amount_cup), 0) AS cash_sales_cup,
         COALESCE(SUM(transfermovil_amount_cup), 0) AS transfermovil_sales_cup,
         COALESCE(SUM(enzona_amount_cup), 0) AS enzona_sales_cup
       FROM sales
       WHERE status = 'COMPLETADA' AND substr(sale_date, 1, 7) = ?`
    )
    .get(period);

  const exemptAgg = db
    .prepare(
      `SELECT COALESCE(SUM(si.line_total_cup), 0) AS exempt_total
       FROM sale_items si
       JOIN sales s ON s.id = si.sale_id
       JOIN products p ON p.id = si.product_id
       WHERE s.status = 'COMPLETADA' AND substr(s.sale_date, 1, 7) = ? AND p.sales_tax_exempt = 1`
    )
    .get(period);

  const expensesAgg = db
    .prepare(
      `SELECT
         COALESCE(SUM(CASE WHEN has_valid_receipt = 1 THEN amount_cup ELSE 0 END), 0) AS deductible_cup,
         COALESCE(SUM(CASE WHEN has_valid_receipt = 0 THEN amount_cup ELSE 0 END), 0) AS non_deductible_cup,
         COALESCE(SUM(amount_cup), 0) AS total_expenses_cup
       FROM expenses
       WHERE substr(expense_date, 1, 7) = ?`
    )
    .get(period);

  const mermasAgg = db
    .prepare(
      `SELECT COALESCE(SUM(total_cost_cup), 0) AS mermas_cup
       FROM inventory_movements
       WHERE type = 'MERMA' AND status = 'APLICADO' AND substr(created_at, 1, 7) = ?`
    )
    .get(period);

  // Use stored payroll run if created for period; else live projection
  const savedPayroll = db.prepare(`SELECT * FROM payroll_runs WHERE period = ?`).get(period);
  const payrollData = savedPayroll
    ? {
        source: savedPayroll.status,
        gross: roundCup(savedPayroll.total_gross_cup),
        vacation: roundCup(savedPayroll.total_vacation_accrual_cup),
        workerSS: roundCup(savedPayroll.total_worker_ss_cup),
        workerIIP: roundCup(savedPayroll.total_worker_iip_cup),
        employerSS: roundCup(savedPayroll.total_employer_ss_cup),
        laborTax: roundCup(savedPayroll.total_labor_tax_cup),
      }
    : (() => {
        const preview = calculatePayrollPreview(db, period);
        return {
          source: 'PROYECCION_AUTOMATICA',
          gross: preview.totals.total_gross_cup,
          vacation: preview.totals.total_vacation_accrual_cup,
          workerSS: preview.totals.total_worker_ss_cup,
          workerIIP: preview.totals.total_worker_iip_cup,
          employerSS: preview.totals.total_employer_ss_cup,
          laborTax: preview.totals.total_labor_tax_cup,
        };
      })();

  const grossSales = roundCup(salesAgg.gross_sales_cup);
  const exemptSales = roundCup(Math.min(grossSales, exemptAgg.exempt_total || 0));
  const taxableSales = roundCup(Math.max(0, grossSales - exemptSales));
  const cogs = roundCup(salesAgg.cogs_cup);
  const grossProfit = roundCup(grossSales - cogs);
  const deductibleExpenses = roundCup(expensesAgg.deductible_cup);
  const nonDeductibleExpenses = roundCup(expensesAgg.non_deductible_cup);
  const mermasCost = roundCup(mermasAgg.mermas_cup);

  // Monthly ONAT taxes
  const salesTax = roundCup((taxableSales * Number(config.sales_tax_pct)) / 100);
  const ctdlTax = roundCup((grossSales * Number(config.local_dev_tax_pct)) / 100);
  const laborTax = payrollData.laborTax;
  const employerSS = payrollData.employerSS;
  const workerWithholdings = roundCup(payrollData.workerSS + payrollData.workerIIP);

  const deductibleTaxes = roundCup(salesTax + ctdlTax + laborTax + employerSS);
  const totalDeductibleCosts = roundCup(
    cogs + deductibleExpenses + mermasCost + payrollData.gross + payrollData.vacation + deductibleTaxes
  );

  const profitBeforeTaxAndReserve = roundCup(grossSales - totalDeductibleCosts);

  let legalReserveProvision = 0;
  let taxableProfit = 0;
  let profitTaxProvision = 0;

  if (config.legal_form === 'MIPYME') {
    // DL 88/2024: Reserve for losses & contingencies up to 20% of social capital (10% of profits)
    const maxReserveBalance = roundCup(Number(config.social_capital_cup) * 0.2);
    const reserveRoom = roundCup(Math.max(0, maxReserveBalance - Number(config.legal_reserve_balance_cup)));
    if (profitBeforeTaxAndReserve > 0 && reserveRoom > 0) {
      legalReserveProvision = roundCup(
        Math.min(reserveRoom, (profitBeforeTaxAndReserve * Number(config.legal_reserve_pct)) / 100)
      );
    }
    taxableProfit = roundCup(Math.max(0, profitBeforeTaxAndReserve - legalReserveProvision));
    profitTaxProvision = roundCup((taxableProfit * Number(config.profit_tax_pct)) / 100);
  } else {
    // TCP Régimen General: Pago a cuenta mensual sobre ingresos/utilidad personal del titular (DJ-08)
    taxableProfit = roundCup(Math.max(0, profitBeforeTaxAndReserve));
    profitTaxProvision = calculateMonthlyIIP(taxableProfit, config.iip_exempt_monthly_cup);
  }

  const netProfitAfterTax = roundCup(
    profitBeforeTaxAndReserve - legalReserveProvision - profitTaxProvision - nonDeductibleExpenses
  );

  const savedFilings = db.prepare(`SELECT * FROM tax_filings WHERE period = ?`).all(period);
  const filingMap = new Map(savedFilings.map((f) => [f.tax_code, f]));

  const rawObligations = [
    {
      tax_code: 'VENTAS_10',
      tax_name: 'Impuesto sobre las Ventas Minoristas',
      onat_paragraph: config.legal_form === 'MIPYME' ? '011402' : '013002',
      frequency: 'Mensual (antes del día 20)',
      law_ref: 'Ley 113 / Ley del Presupuesto',
      taxable_base_cup: taxableSales,
      rate_pct: Number(config.sales_tax_pct),
      amount_cup: salesTax,
      due_date: dueDate,
    },
    {
      tax_code: 'CTDL_1',
      tax_name: 'Contribución Territorial para el Desarrollo Local',
      onat_paragraph: '073012',
      frequency: 'Mensual (antes del día 20)',
      law_ref: 'Ley 113 — Presupuesto Municipal',
      taxable_base_cup: grossSales,
      rate_pct: Number(config.local_dev_tax_pct),
      amount_cup: ctdlTax,
      due_date: dueDate,
    },
    {
      tax_code: 'IUFT_5',
      tax_name: 'Impuesto por la Utilización de la Fuerza de Trabajo',
      onat_paragraph: '061032',
      frequency: 'Mensual (antes del día 20)',
      law_ref: 'Ley 113 Art. 225',
      taxable_base_cup: roundCup(payrollData.gross + payrollData.vacation),
      rate_pct: Number(config.labor_force_tax_pct),
      amount_cup: laborTax,
      due_date: dueDate,
    },
    {
      tax_code: 'SS_EMPLEADOR',
      tax_name: 'Contribución a la Seguridad Social (Entidad)',
      onat_paragraph: '082013',
      frequency: 'Mensual (antes del día 20)',
      law_ref: 'Ley 105 / Ley 113 (12.5% + 1.5%)',
      taxable_base_cup: payrollData.gross,
      rate_pct: Number(config.employer_ss_pct),
      amount_cup: employerSS,
      due_date: dueDate,
    },
    {
      tax_code: 'RETENCION_SS_IIP',
      tax_name: 'Retenciones a Trabajadores (Seg. Social 5% + Ingresos Personales)',
      onat_paragraph: '082053 / 051052',
      frequency: 'Mensual (antes del día 20)',
      law_ref: 'Ley 113 — Agente Retenedor',
      taxable_base_cup: payrollData.gross,
      rate_pct: payrollData.gross > 0 ? roundCup((workerWithholdings / payrollData.gross) * 100) : 0,
      amount_cup: workerWithholdings,
      due_date: dueDate,
    },
    {
      tax_code: 'UTILIDADES_35',
      tax_name:
        config.legal_form === 'MIPYME'
          ? 'Provisión Impuesto sobre Utilidades (MIPYME)'
          : 'Provisión Impuesto sobre Ingresos Personales Titular (TCP - DJ-08)',
      onat_paragraph: config.legal_form === 'MIPYME' ? '040082' : '051012',
      frequency: config.legal_form === 'MIPYME' ? 'Trimestral / DJ Anual' : 'Pago a cuenta / DJ-08 Anual',
      law_ref: config.legal_form === 'MIPYME' ? 'Ley 113 / DL 88/2024' : 'Ley 113 / DL 90/2024',
      taxable_base_cup: taxableProfit,
      rate_pct:
        config.legal_form === 'MIPYME'
          ? Number(config.profit_tax_pct)
          : taxableProfit > 0
          ? roundCup((profitTaxProvision / taxableProfit) * 100)
          : 0,
      amount_cup: profitTaxProvision,
      due_date: dueDate,
    },
  ];

  const obligations = rawObligations.map((ob) => {
    const saved = filingMap.get(ob.tax_code);
    return {
      ...ob,
      filing_id: saved?.id || null,
      status: saved?.status || 'CALCULADO',
      paid_amount_cup: saved?.status === 'PAGADO' ? roundCup(saved.amount_cup) : 0,
      payment_ref: saved?.payment_ref || '',
      paid_at: saved?.paid_at || null,
    };
  });

  const totalOnatPeriod = roundCup(obligations.reduce((a, o) => a + o.amount_cup, 0));
  const totalPaidPeriod = roundCup(obligations.reduce((a, o) => a + o.paid_amount_cup, 0));
  const electronicSales = roundCup(
    Number(salesAgg.transfermovil_sales_cup) + Number(salesAgg.enzona_sales_cup)
  );
  const electronicSharePct = grossSales > 0 ? roundCup((electronicSales / grossSales) * 100) : 0;

  return {
    period,
    legal_form: config.legal_form,
    due_date: dueDate,
    payroll_source: payrollData.source,
    income_statement: {
      sales_count: Number(salesAgg.sales_count || 0),
      subtotal_cup: roundCup(salesAgg.subtotal_cup),
      qr_discount_cup: roundCup(salesAgg.qr_discount_cup),
      gross_sales_cup: grossSales,
      taxable_sales_cup: taxableSales,
      exempt_sales_cup: exemptSales,
      cash_sales_cup: roundCup(salesAgg.cash_sales_cup),
      transfermovil_sales_cup: roundCup(salesAgg.transfermovil_sales_cup),
      enzona_sales_cup: roundCup(salesAgg.enzona_sales_cup),
      electronic_sales_cup: electronicSales,
      electronic_share_pct: electronicSharePct,
      cogs_cup: cogs,
      gross_profit_cup: grossProfit,
      deductible_expenses_cup: deductibleExpenses,
      non_deductible_expenses_cup: nonDeductibleExpenses,
      mermas_cup: mermasCost,
      payroll_gross_cup: payrollData.gross,
      payroll_vacation_cup: payrollData.vacation,
      deductible_taxes_cup: deductibleTaxes,
      profit_before_tax_cup: profitBeforeTaxAndReserve,
      legal_reserve_provision_cup: legalReserveProvision,
      taxable_profit_cup: taxableProfit,
      profit_tax_provision_cup: profitTaxProvision,
      net_profit_cup: netProfitAfterTax,
    },
    obligations,
    totals: {
      total_onat_cup: totalOnatPeriod,
      total_paid_cup: totalPaidPeriod,
      total_pending_cup: roundCup(Math.max(0, totalOnatPeriod - totalPaidPeriod)),
    },
  };
}

/**
 * Automated Cuban Legal & Internal Control Inspector (ONAT / BCC / MFP / DIS / MTSS).
 */
export function runComplianceAudit(db) {
  const config = getConfig(db);
  const today = getTodayIso();
  const checks = [];

  // 1. Forma jurídica y dotación (DL 88/2024 MIPYME vs DL 90/2024 TCP)
  const activeUsers = db.prepare(`SELECT * FROM users WHERE active = 1`).all();
  const hiredCount = activeUsers.filter((u) => u.role !== 'jefe').length;
  const totalStaff = activeUsers.length;
  const roleCounts = {
    jefe: activeUsers.filter((u) => u.role === 'jefe').length,
    economico: activeUsers.filter((u) => u.role === 'economico').length,
    almacenero: activeUsers.filter((u) => u.role === 'almacenero').length,
    vendedor: activeUsers.filter((u) => u.role === 'vendedor').length,
  };
  const shifts = db.prepare(`SELECT * FROM shift_templates WHERE active = 1`).all();
  const incompleteShifts = shifts.filter((st) => {
    const sellers = activeUsers.filter((u) => u.role === 'vendedor' && u.shift_template_id === st.id).length;
    return sellers !== st.required_sellers;
  });

  if (config.legal_form === 'TCP' && hiredCount > 3) {
    checks.push({
      code: 'DL90_PLANTILLA',
      authority: 'MTSS / ONAT',
      law: 'Decreto-Ley 90/2024 y Decreto-Ley 88/2024',
      title: 'Límite de trabajadores contratados en TCP superado',
      status: 'CRITICO',
      detail: `Cuenta con ${hiredCount} trabajadores contratados además del titular. El DL 90/2024 solo permite hasta 3 contratados para un TCP; con esta plantilla (2 vendedores/turno + almacenero + económico) debe operar como Micro-MIPYME (1 a 10 personas, DL 88/2024).`,
    });
  } else if (config.legal_form === 'MIPYME' && totalStaff > 10) {
    checks.push({
      code: 'DL88_MICRO',
      authority: 'MEP / ONAT',
      law: 'Decreto-Ley 88/2024 (MIPYMES)',
      title: 'Plantilla supera rango de Microempresa (1–10)',
      status: 'ALERTA',
      detail: `Tiene ${totalStaff} personas activas; supera las 10 plazas de Microempresa y pasa a Pequeña Empresa (11–35).`,
    });
  } else if (
    roleCounts.jefe < 1 ||
    roleCounts.economico < 1 ||
    roleCounts.almacenero < 1 ||
    incompleteShifts.length > 0
  ) {
    checks.push({
      code: 'ESTRUCTURA_ROLES',
      authority: 'Control Interno',
      law: 'DL 88/2024 / Res. 60/22 CGR',
      title: 'Plantilla por puestos o turnos incompleta',
      status: 'ALERTA',
      detail: `Activos: ${roleCounts.jefe} Jefe, ${roleCounts.economico} Económico, ${roleCounts.almacenero} Almacenero, ${roleCounts.vendedor} Vendedores. Turnos con dotación distinta a 2 vendedores: ${incompleteShifts.map((s) => s.name).join(', ') || 'ninguno'}.`,
    });
  } else {
    checks.push({
      code: 'DL88_PLANTILLA',
      authority: 'MEP / MTSS',
      law: config.legal_form === 'MIPYME' ? 'Decreto-Ley 88/2024 (Micro-MIPYME)' : 'Decreto-Ley 90/2024 (TCP)',
      title: 'Forma jurídica y segregación de puestos en regla',
      status: 'OK',
      detail: `${config.legal_form} con ${totalStaff} integrantes (${roleCounts.jefe} Jefe, ${roleCounts.economico} Económico, ${roleCounts.almacenero} Almacenero y 2 vendedores asignados por turno en ${shifts.length} turno(s)).`,
    });
  }

  // 2. Cuenta Bancaria Fiscal y Pasarelas QR (Res. 111/2023 BCC)
  const hasBanking =
    String(config.fiscal_account_cup || '').replace(/\D/g, '').length >= 16 &&
    Boolean(config.transfermovil_merchant_code?.trim()) &&
    Boolean(config.enzona_merchant_code?.trim()) &&
    Boolean(config.nit?.trim());

  checks.push({
    code: 'BCC_PASARELAS',
    authority: 'BCC / ONAT',
    law: 'Resolución 111/2023 BCC (Bancarización)',
    title: 'Cuenta Bancaria Fiscal y cobro QR obligatorio',
    status: hasBanking ? 'OK' : 'CRITICO',
    detail: hasBanking
      ? `Cuenta Fiscal CUP activa en ${config.bank_name} (${config.fiscal_account_cup}), QR Transfermóvil (${config.transfermovil_merchant_code}) y EnZona (${config.enzona_merchant_code}) habilitados.`
      : 'Falta configurar Cuenta Bancaria Fiscal de 16 dígitos, NIT o códigos de comercio Transfermóvil/EnZona obligatorios para venta minorista.',
  });

  // 3. Depósitos de efectivo en banco (Res. 111/2023 BCC)
  const pendingDeposits = db
    .prepare(`SELECT * FROM bank_deposits WHERE status = 'PENDIENTE'`)
    .all();
  const overdueDeposits = pendingDeposits.filter((d) => d.due_date < today);
  const pendingDepositSum = roundCup(pendingDeposits.reduce((a, d) => a + d.amount_cup, 0));

  checks.push({
    code: 'BCC_DEPOSITOS',
    authority: 'BCC',
    law: 'Resolución 111/2023 BCC — Límite de Caja y Depósito',
    title: 'Depósito de efectivo recaudado en Cuenta Fiscal',
    status: overdueDeposits.length > 0 ? 'CRITICO' : pendingDeposits.length > 0 ? 'ALERTA' : 'OK',
    detail:
      overdueDeposits.length > 0
        ? `Existen ${overdueDeposits.length} orden(es) de depósito bancario vencidas por depositar en ${config.bank_name}.`
        : pendingDeposits.length > 0
        ? `${pendingDeposits.length} orden(es) de depósito pendiente(s) por ${pendingDepositSum.toFixed(2)} CUP dentro del plazo del próximo día hábil bancario.`
        : 'Todo el efectivo excedente del fondo fijo de caja se encuentra depositado en la Cuenta Bancaria Fiscal.',
  });

  // 4. Pagos en efectivo > 5,000 CUP a proveedores
  const limit = Number(config.max_cash_provider_payment_cup || 5000);
  const cashViolations = db
    .prepare(
      `SELECT COUNT(*) AS cnt FROM (
         SELECT id FROM inventory_movements WHERE type = 'RECEPCION' AND payment_method = 'EFECTIVO' AND total_cost_cup > ?
         UNION ALL
         SELECT id FROM expenses WHERE payment_method = 'EFECTIVO' AND amount_cup > ?
       )`
    )
    .get(limit, limit);

  checks.push({
    code: 'BCC_LIMITE_5000',
    authority: 'BCC / ONAT',
    law: 'Resolución 111/2023 BCC — Pagos entre actores',
    title: `Tope de ${limit.toFixed(0)} CUP en pagos en efectivo a proveedores`,
    status: cashViolations.cnt > 0 ? 'CRITICO' : 'OK',
    detail:
      cashViolations.cnt > 0
        ? `Se detectaron ${cashViolations.cnt} pagos en efectivo superiores a ${limit} CUP. Deben liquidarse por vía electrónica.`
        : `100% de compras de almacén y gastos superiores a ${limit.toFixed(0)} CUP liquidados por vía electrónica (bloqueo automático activo).`,
  });

  // 5. Precios Minoristas Topados (Res. 225/2024 MFP / Decreto 30)
  const products = db.prepare(`SELECT * FROM products WHERE active = 1`).all();
  const sheets = products.map((p) => ({ product: p, sheet: calculateCostSheet(p, config) }));
  const capViolations = sheets.filter((s) => s.sheet.exceeds_cap);
  const marginViolations = sheets.filter((s) => s.sheet.exceeds_margin);
  const cappedCount = products.filter((p) => p.is_price_capped).length;

  checks.push({
    code: 'MFP_TOPES_225',
    authority: 'MFP / DIS',
    law: 'Resolución 225/2024 MFP y Decreto 30/2021',
    title: 'Cumplimiento de precios minoristas topados y tablilla en CUP',
    status: capViolations.length > 0 ? 'CRITICO' : 'OK',
    detail:
      capViolations.length > 0
        ? `Riesgo de multa Decreto 30: ${capViolations.map((c) => c.product.name).join(', ')} excede(n) el precio topado oficial.`
        : `Los ${cappedCount} productos básicos regulados en catálogo respetan estrictamente los precios máximos en CUP y la Tablilla Oficial está actualizada.`,
  });

  // 6. Fichas de Costo y Margen Comercial <= 30%
  checks.push({
    code: 'MFP_MARGEN_30',
    authority: 'MFP',
    law: `Normativa de Precios MFP (Margen máx. ${config.max_regulated_margin_pct}%)`,
    title: 'Fichas de Costo y margen de utilidad sobre costos y gastos',
    status: marginViolations.length > 0 ? 'ALERTA' : 'OK',
    detail:
      marginViolations.length > 0
        ? `${marginViolations.length} producto(s) superan el ${config.max_regulated_margin_pct}% de margen comercial: ${marginViolations.map((m) => m.product.name).join(', ')}.`
        : `Los ${products.length} productos activos cuentan con Ficha de Costo automatizada y margen dentro del ${config.max_regulated_margin_pct}%.`,
  });

  // 7. Código de Trabajo (Ley 116) — Salario mínimo y contratos
  const underpaid = activeUsers.filter((u) => u.base_salary_cup < Number(config.min_wage_cup));
  checks.push({
    code: 'MTSS_LEY116',
    authority: 'MTSS',
    law: 'Ley 116 — Código de Trabajo',
    title: 'Salario mínimo legal, contratos y provisión de vacaciones (9.09%)',
    status: underpaid.length > 0 ? 'CRITICO' : 'OK',
    detail:
      underpaid.length > 0
        ? `${underpaid.length} trabajador(es) con salario inferior al mínimo legal de ${config.min_wage_cup} CUP.`
        : `Todos los trabajadores perciben salario superior al mínimo legal (${config.min_wage_cup} CUP/mes), con CI, contrato escrito y acumulación automática del 9.09% de vacaciones.`,
  });

  // 8. Tributos ONAT vencidos
  const overdueTaxes = db
    .prepare(`SELECT * FROM tax_filings WHERE status = 'PENDIENTE' AND due_date < ?`)
    .all(today);
  checks.push({
    code: 'ONAT_LEY113',
    authority: 'ONAT',
    law: 'Ley 113 del Sistema Tributario',
    title: 'Declaración y pago oportuno de tributos (día 20)',
    status: overdueTaxes.length > 0 ? 'CRITICO' : 'OK',
    detail:
      overdueTaxes.length > 0
        ? `Atención: ${overdueTaxes.length} obligación(es) ONAT vencida(s) con riesgo de recargo por mora.`
        : 'Sin deudas tributarias vencidas ante la ONAT. Los tributos del mes en curso se calculan y provisionan automáticamente con cada venta.',
  });

  // 9. Control interno: Mermas pendientes y faltantes de caja
  const pendingMermas = db
    .prepare(`SELECT COUNT(*) AS cnt FROM inventory_movements WHERE status = 'PENDIENTE_APROBACION'`)
    .get();
  const unvalidatedRegisters = db
    .prepare(`SELECT COUNT(*) AS cnt FROM shift_registers WHERE status = 'ARQUEADA' AND ABS(cash_difference_cup) > 0.5`)
    .get();

  checks.push({
    code: 'CGR_CONTROL_INTERNO',
    authority: 'Economía Interna',
    law: 'NCIF / Modelos SC-2-04, SC-2-09, SC-2-14, SC-2-16 e IPV',
    title: 'Cuadres de caja, IPV y ajustes de inventario',
    status: pendingMermas.cnt > 0 || unvalidatedRegisters.cnt > 0 ? 'ALERTA' : 'OK',
    detail:
      pendingMermas.cnt > 0 || unvalidatedRegisters.cnt > 0
        ? `Pendientes de revisión: ${pendingMermas.cnt} ajuste(s)/merma(s) SC-2-16 y ${unvalidatedRegisters.cnt} arqueo(s) de caja con diferencia.`
        : 'Todos los modelos de almacén, IPV de turno y arqueos de caja están conciliados y contabilizados.',
  });

  // 10. Vencimientos e inocuidad en almacén/mostrador
  const in15Days = new Date();
  in15Days.setUTCDate(in15Days.getUTCDate() + 15);
  const limitDate = in15Days.toISOString().slice(0, 10);
  const expired = products.filter(
    (p) => p.next_expiry_date && p.next_expiry_date < today && p.warehouse_stock + p.kiosk_stock > 0
  );
  const expiringSoon = products.filter(
    (p) =>
      p.next_expiry_date &&
      p.next_expiry_date >= today &&
      p.next_expiry_date <= limitDate &&
      p.warehouse_stock + p.kiosk_stock > 0
  );

  checks.push({
    code: 'DIS_INOCUIDAD',
    authority: 'DIS / Salud Pública',
    law: 'Protección al Consumidor (Res. 54 MINCIN)',
    title: 'Vigencia sanitaria y rotación FEFO de lotes',
    status: expired.length > 0 ? 'CRITICO' : expiringSoon.length > 0 ? 'ALERTA' : 'OK',
    detail:
      expired.length > 0
        ? `Prohibida su venta: ${expired.map((p) => p.name).join(', ')} con fecha vencida. Dar baja por merma SC-2-16 de inmediato.`
        : expiringSoon.length > 0
        ? `${expiringSoon.length} producto(s) vencen en ≤15 días (${expiringSoon.map((p) => p.name).join(', ')}). Priorizados por despacho FEFO.`
        : 'Todos los lotes en almacén y mostrador cuentan con fecha de vencimiento vigente.',
  });

  const criticalCount = checks.filter((c) => c.status === 'CRITICO').length;
  const warningCount = checks.filter((c) => c.status === 'ALERTA').length;
  const okCount = checks.filter((c) => c.status === 'OK').length;
  const score = Math.max(0, Math.round(((okCount + warningCount * 0.6) / checks.length) * 100));
  const overall = criticalCount > 0 ? 'RIESGO_MULTA' : warningCount > 0 ? 'ATENCION' : 'CUMPLIENDO';

  return {
    checked_at: new Date().toISOString(),
    score,
    overall,
    ok_count: okCount,
    warning_count: warningCount,
    critical_count: criticalCount,
    checks,
  };
}
